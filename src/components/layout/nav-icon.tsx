export interface NavIconProps extends LucideProps {
  name: string;
}

/** Renderiza o ícone pelo nome (string de NavItem.icon). Nome desconhecido cai em um círculo. */
export function NavIcon({ name, ...props }: NavIconProps) {
  const Icon = NAV_ICONS[name] ?? Circle;
  return <Icon aria-hidden {...props} />;
}
